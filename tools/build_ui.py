"""Bundle local UI dependencies into routes supported by already-running servers.

Run with the bundled Python after editing ui/src or the feature source files.
No Node packages or network access are required.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUNDLES = {
    'ui/sql_completion.js': ['ui/theme.js', 'ui/src/sql_completion.js'],
    'ui/editor.js': ['ui/vendor/sql-formatter.min.js', 'ui/sql_presentation.js', 'ui/src/editor.js',
                     'ui/query_builder_query.js', 'ui/query_builder.js',
                     'ui/vendor/echarts.min.js', 'ui/charts.js'],
    'ui/workbench.css': ['ui/src/workbench.css', 'ui/theme.css', 'ui/query_builder.css', 'ui/charts.css'],
}


def build(check=False):
    for output, sources in BUNDLES.items():
        content = '/* Generated by tools/build_ui.py; edit the source files listed there. */\n'
        separator = '\n;\n' if output.endswith('.js') else '\n'
        content += separator.join((ROOT / source).read_text(encoding='utf-8').rstrip() for source in sources)
        content += '\n'
        if check:
            if (ROOT / output).read_text(encoding='utf-8') != content:
                raise SystemExit(f'{output} is out of date; run tools/build_ui.py')
        else:
            (ROOT / output).write_text(content, encoding='utf-8')


if __name__ == '__main__':
    import sys
    build(check='--check' in sys.argv)
