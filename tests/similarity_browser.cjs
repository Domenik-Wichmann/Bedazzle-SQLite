const fs=require('fs'),path=require('path'),assert=require('assert/strict');
process.env.PLAYWRIGHT_BROWSERS_PATH=path.resolve('.test-tools/browsers');
const {chromium}=require('../.test-tools/node_modules/playwright');
const session=JSON.parse(fs.readFileSync(process.env.BEDAZZLE_TEST_SESSION||'workspace/http-smoke-session.json'));
const fixture=JSON.parse(fs.readFileSync('workspace/module-smoke-fixture.json'));
(async()=>{
 const browser=await chromium.launch(),page=await browser.newPage({viewport:{width:1440,height:1050}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 const idle=async()=>{await page.locator('#job-strip').waitFor({state:'hidden',timeout:60000});await page.waitForTimeout(150);};
 try{
  await page.goto(session.url+'/#'+session.token);await page.locator('#module-menu option[value="image_checker"]').waitFor({state:'attached'});
  await page.locator('#workspace-nav').click();await page.locator('.workspace-card.current .button.primary').click();
  const paths=['/scene?token=similarity_secret','/scene-jpeg','/scene-small','/scene-edit','/noise','/blank','/transparent'];
  await page.locator('#sql-editor').fill(`SELECT * FROM (VALUES ${paths.map((p,i)=>`('SKU-${i}','${fixture.url+p}')`).join(',')}) t(sku,image)`);
  await page.locator('#run-query').click();await idle();
  await page.locator('#module-menu').selectOption('image_checker');await page.locator('#module-option-url_columns').waitFor();
  await page.locator('#module-option-record_id').selectOption('sku');
  await page.getByText('Limits and networking',{exact:true}).click();await page.locator('#module-option-allow_private').check();
  await page.locator('#module-start').click();await page.waitForFunction(()=>!moduleState.busy&&moduleState.run?.status==='completed',{},{timeout:60000});
  assert.equal(await page.evaluate(()=>moduleState.run.summary.similarity.pairs),6);
  await page.evaluate(async()=>{const result=await runJob('module_manage',{operation:'similarity_pairs',run_id:moduleState.run.id,decision:'all'});for(const pair of result.pairs)await runJob('module_manage',{operation:'similarity_decide',run_id:moduleState.run.id,pair_id:pair.id,decision:'unreviewed',note:''});});
  await page.getByRole('button',{name:'Compare 3 matches',exact:true}).first().click();await idle();
  assert.equal(await page.locator('.module-pair').count(),3);
  await page.getByRole('button',{name:'Show matches for all images',exact:true}).click();await idle();
  await page.getByLabel('Pair review status',{exact:true}).selectOption('unreviewed');await idle();
  assert.equal(await page.locator('.module-pair').count(),6);
  assert((await page.locator('#module-similarity-pairs').textContent()).includes('not product identity'));
  assert(!(await page.locator('#module-similarity-pairs').textContent()).includes('similarity_secret'));
  const card=page.locator('.module-pair').first();
  await card.getByRole('button',{name:'Load both previews',exact:true}).click();await idle();
  assert.equal(await card.locator('img').count(),2);
  const firstId=await card.getAttribute('data-pair-id');
  await card.getByLabel(`Decision for pair ${firstId}`,{exact:true}).selectOption('similar');
  await card.getByLabel(`Note for pair ${firstId}`,{exact:true}).fill('Review fixture: same product');
  await page.screenshot({path:'workspace/verification/image-similarity-desktop.png'});
  await card.getByRole('button',{name:'Save review',exact:true}).click();await idle();
  assert.equal(await page.locator('.module-pair').count(),5);
  await page.getByLabel('Pair review status',{exact:true}).selectOption('similar');await idle();
  assert.equal(await page.locator('.module-pair').count(),1);
  await page.getByText('Adjust matching — uses saved fingerprints, no downloads',{exact:true}).click();
  await page.getByLabel('Similarity sensitivity',{exact:true}).selectOption('strict');
  await page.getByRole('button',{name:'Rebuild matches',exact:true}).click();await idle();
  assert.equal(await page.locator('.module-pair').count(),1);
  assert.equal(await page.locator('.module-pair input[type=text]').inputValue(),'Review fixture: same product');
  const output=path.resolve(session.workspace,'similarity-pairs-'+Date.now()+'.csv');
  await page.getByRole('button',{name:'Export pairs…',exact:true}).click();
  await page.locator('#export-format').selectOption('csv');await page.locator('#export-path').fill(output);await page.locator('#confirm-export').click();await idle();
  const csv=fs.readFileSync(output,'utf8');assert(!csv.includes('similarity_secret'));assert(csv.includes('left_record_id'));assert(csv.includes('Review fixture: same product'));assert.equal(csv.trim().split('\n').length,2);
  await page.setViewportSize({width:390,height:844});await page.screenshot({path:'workspace/verification/image-similarity-mobile.png'});
  assert(await page.locator('#module-dialog').evaluate(e=>e.getBoundingClientRect().width<=innerWidth));
  await page.setViewportSize({width:1440,height:1050});
  const old=await page.evaluate(()=>moduleState.run.id);
  await page.getByRole('button',{name:'Recheck these images',exact:true}).click();await page.waitForFunction(old=>!moduleState.busy&&moduleState.run?.status==='completed'&&moduleState.run.id!==old,old,{timeout:60000});
  await page.getByRole('button',{name:'Review similar pairs',exact:true}).click();await idle();
  await page.getByLabel('Pair review status',{exact:true}).selectOption('similar');await idle();
  assert.equal(await page.locator('.module-pair').count(),1);
  console.log('PASS: visual candidates with different hashes, side-by-side safe previews, review decisions, rebuild without downloads, redacted pair export, responsive layout and targeted recheck preserving decisions');
  assert.deepEqual(errors,[]);
 }catch(error){console.error('Module error:',await page.locator('#module-error').textContent());throw error;}
 finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
